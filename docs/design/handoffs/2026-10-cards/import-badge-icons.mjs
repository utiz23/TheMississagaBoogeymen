#!/usr/bin/env node
/**
 * Imports the operator's badge icons (spec D14) from a folder of SVGs into
 * apps/web/public/images/badges/icons/<family id>.svg as one-colour masks
 * (see badge-icon-mask.mjs) and writes apps/web/src/components/badges/badge-icons.ts.
 * Families without a file keep their lucide placeholder (operator 2026-10-08:
 * Dekes, Desperation Saves and Shutouts keep theirs).
 *
 * Usage (repo root): node docs/design/handoffs/2026-10-cards/import-badge-icons.mjs docs/design/handoffs/2026-10-cards/badge-icons-src
 * (the operator's originals, 2026-10-08)
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { toMaskSvg } from './badge-icon-mask.mjs'

/**
 * Operator file name (without .svg) → badge family and how the icon sits in it,
 * tuned by eye on /preview/badges:
 *   scale   size relative to the badge's standard icon box (default 1)
 *   weight  round same-colour stroke (viewBox units) for thin solid art
 *   solid   light paint is solid too (no cut-outs): a filled silhouette
 *   invert  light paint is the shape, dark lines are cut-out gaps
 *   offsetX / offsetY  shift right / down, as a share of the icon box; the badge
 *           face clips the overflow, so the icon can run off an edge
 */
const FILE_TO_FAMILY = {
  '3v3': { id: 'p3v3' },
  '6sGamescompleted': { id: 'p6v6' },
  Goaliegamescompleted: { id: 'p6g', scale: 1.15 },
  // Wins: one solid laurel, no cut-outs — thickened so it holds at 28–34 px.
  Wins: { id: 'pwins', scale: 1.35, weight: 1.2 },
  // Goals: large, its base strip runs off the bottom of the badge face while both rows of
  // square panes stay inside the round face (operator, 2026-10-08).
  Goals: { id: 'pgoals', scale: 1.6, offsetY: 0.2 },
  Assists: { id: 'pasts' },
  Shots: { id: 'pshots' },
  Hattricks: { id: 'pht' },
  // Breakaways is an outline drawing; Breakaways-solid.svg is derived from it with the
  // links filled (outer contours solid, slots kept, tracing specks dropped).
  Breakaways: { skip: 'superseded by Breakaways-solid.svg' },
  'Breakaways-solid': { id: 'pbrk' },
  // Hits: centred on the hammer head; the handle runs off the badge (operator, 2026-10-08).
  Hits: { id: 'phits', scale: 1.5, offsetX: -0.17, offsetY: 0.24 },
  Faceoffs: { id: 'pfo' },
  Takeaways: { id: 'ptka' },
  Blocks: { id: 'pblk' },
  // Fights: inverted so the gloves read filled, their outlines kept as gaps (operator,
  // 2026-10-08). Fights-filled.svg adds the back glove's missing interior fills
  // (fill-outline-interiors.py Fights.svg Fights-filled.svg 0).
  Fights: { skip: 'superseded by Fights-filled.svg' },
  'Fights-filled': { id: 'pfight', invert: true, scale: 1.35 },
  Gstarts: { id: 'gg' },
  Gwins: { id: 'gw' },
  Saves: { id: 'gsv' },
  Pokechecks: { id: 'gpoke' },
}

const src = process.argv[2]
if (src === undefined) {
  console.error('usage: import-badge-icons.mjs <folder of SVGs>')
  process.exit(2)
}
const OUT = 'apps/web/public/images/badges/icons'
const problems = []
const written = {}
const files = readdirSync(src).filter((f) => f.toLowerCase().endsWith('.svg'))
for (const file of files) {
  const entry = FILE_TO_FAMILY[file.replace(/\.svg$/i, '')]
  if (entry !== undefined && 'skip' in entry) continue
  if (entry === undefined) {
    problems.push(`${file}: unknown file name (add it to FILE_TO_FAMILY)`)
    continue
  }
  const {
    id: family,
    scale = 1,
    weight = 0,
    solid = false,
    invert = false,
    offsetX = 0,
    offsetY = 0,
  } = entry
  try {
    written[family] = {
      svg: toMaskSvg(readFileSync(join(src, file), 'utf8'), { weight, solid, invert }),
      scale,
      offsetX,
      offsetY,
    }
  } catch (e) {
    problems.push(`${file}: ${e instanceof Error ? e.message : String(e)}`)
  }
}
if (problems.length > 0) {
  console.error(problems.join('\n'))
  process.exit(1)
}

rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })
const ids = Object.keys(written).sort()
for (const id of ids) writeFileSync(join(OUT, `${id}.svg`), written[id].svg)
writeFileSync(
  'apps/web/src/components/badges/badge-icons.ts',
  [
    '/**',
    " * GENERATED by docs/design/handoffs/2026-10-cards/import-badge-icons.mjs from the operator's",
    ' * badge icons (spec D14). Families listed here draw /images/badges/icons/<id>.svg',
    ' * as a tinted mask; the rest keep their lucide placeholder. Do not edit by hand.',
    ' */',
    "import type { BadgeFamilyId } from '@eanhl/db/cards'",
    '',
    'export interface BadgeIcon {',
    '  src: string',
    "  /** Size relative to the badge's standard icon box. */",
    '  scale: number',
    '  /** Shift right / down as a share of the icon box; the badge face clips the overflow. */',
    '  offsetX: number',
    '  offsetY: number',
    '}',
    '',
    'export const BADGE_ICONS: Readonly<Partial<Record<BadgeFamilyId, BadgeIcon>>> = {',
    ...ids.map(
      (id) =>
        `  ${id}: { src: '/images/badges/icons/${id}.svg', scale: ${String(written[id].scale)}, offsetX: ${String(written[id].offsetX)}, offsetY: ${String(written[id].offsetY)} },`,
    ),
    '}',
    '',
  ].join('\n'),
)
console.log(`${String(ids.length)} icons written: ${ids.join(' ')}`)

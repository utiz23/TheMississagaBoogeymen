// One-off port: reads the design bundle's card-data.js and writes
// apps/web/src/components/cards/card-themes.ts (the 10 shipping themes, tier
// chip/silhouette styles and position colours).
// Usage: node docs/design/handoffs/2026-10-cards/port-card-themes.mjs [out]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = process.argv[2] ?? join(here, '../../../../apps/web/src/components/cards/card-themes.ts')
globalThis.window = {}
// eslint-disable-next-line no-eval
;(0, eval)(readFileSync(join(here, 'card-data.js'), 'utf8'))
const D = globalThis.window.BGM_CARD

const ORDER = ['away', 'home', 'alternate', 'carbon', 'futureB', 'frozen', 'futureC', 'inferno', 'stormLive', 'olympus']
const DEAD = ['texture', 'unlockBg', 'hud', 'crack', 'noCrack', 'fire', 'flame']
// PlayerCard.dc.html L326 defaults, merged under each theme's own tokens.
const tkDefaults = (th) => ({
  ink: '#f4f4f5', sv: '#e4e4e7', sl: '#71717a', rec: '#71717a', pct: '#d4d4d8',
  line: 'rgba(63,63,70,0.4)', lead: '#e84131', leadL: 'rgba(232,65,49,0.7)',
  pipOn: th.pip || '#e84131', pipOff: '#2f2c2d', edition: '#6e6b6c', arch: '#a1a1aa',
  backLabel: '#71717a', backHead: '#6e6b6c', backFoot: '#6e6b6c',
})
// Design-bundle asset paths → the site's public folder (round 2 produces the files).
const rewrite = (v) =>
  typeof v === 'string'
    ? v.replace(/(['"(]|^)assets\/([\w.-]+)/g, (_, pre, file) => `${pre}/images/cards/${file}`)
    : Array.isArray(v)
      ? v.map(rewrite)
      : v && typeof v === 'object'
        ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, rewrite(x)]))
        : v

const themes = {}
for (const key of ORDER) {
  const th = { ...D.THEMES[key] }
  for (const k of DEAD) delete th[k]
  delete th.pip
  th.tk = { ...tkDefaults(D.THEMES[key]), ...(D.THEMES[key].tk ?? {}) }
  themes[key] = rewrite(th)
}
const tiers = {}
for (let n = 1; n <= 6; n++) tiers[n] = { chip: D.TIERS[n].chip, silh: D.TIERS[n].silh }

const ts = `// GENERATED by docs/design/handoffs/2026-10-cards/port-card-themes.mjs — do not edit by hand.
// Source: card-data.js THEMES (10 shipping keys), TIERS (chip, silhouette size) and POS.
import type { CardThemeKey, CardTier } from '@eanhl/db/cards'
import type { CardTheme, CardTierStyle } from './card-theme-types'

export const CARD_THEMES: Readonly<Record<CardThemeKey, CardTheme>> = ${JSON.stringify(themes, null, 2)}

export const CARD_TIER_STYLE: Readonly<Record<CardTier, CardTierStyle>> = ${JSON.stringify(tiers, null, 2)}

/** Position chip colours (design POS map; D = the LD colour, as the site's --pos-d alias). */
export const CARD_POS_COLORS: Readonly<Record<string, string>> = ${JSON.stringify({ ...D.POS, D: D.POS.LD }, null, 2)}
`
writeFileSync(out, ts)
console.log(`wrote ${out}`)

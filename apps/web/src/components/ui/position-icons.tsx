/**
 * Position glyphs for the hero position pill (Hero Pills design,
 * `pill-icons.js`). All paint in `currentColor`; the dark fills inside the
 * mask and shield are the chassis background, so the glyph reads as cut out.
 * Wing and defense glyphs are drawn facing right-wing / right-defense; the
 * left side is the same glyph mirrored (`flip`).
 */

export type PositionGlyph = 'center' | 'wing' | 'defense' | 'goalie'

export function PositionIcon({ glyph, flip = false }: { glyph: PositionGlyph; flip?: boolean }) {
  const icon =
    glyph === 'center' ? (
      <PosCIcon />
    ) : glyph === 'goalie' ? (
      <PosGIcon />
    ) : glyph === 'wing' ? (
      <PosWIcon />
    ) : (
      <PosDIcon />
    )
  return <span className={flip ? 'pos-glyph flip' : 'pos-glyph'}>{icon}</span>
}

